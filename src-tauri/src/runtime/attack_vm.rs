//! The attack VM beside a VM lab: the learner's own machine, a Vagrant box chosen in Settings
//! (Kali by default), with the provider's NAT adapter for the internet (tools get installed)
//! and a NIC on every lab network, joined through the same internal-network names the lab's
//! Vagrantfile uses. Launcher-owned, nothing in the lab's spec: started with the lab (or on
//! demand from the lab page), destroyed with it, reached with `vagrant ssh`. The same status
//! shape as the container attack box, so the lab page and the diagram treat both alike.

use std::collections::HashSet;
use std::net::Ipv4Addr;
use std::path::{Path, PathBuf};

use super::exegol::{self, ExegolStatus};
use super::model::Park;
use super::providers::Provider;
use super::{ssh, vm};
use crate::error::{Error, Result};
use crate::exec::{run_read, stream};

/// The attacker's own Vagrant environment, inside the lab folder (removed with the lab).
const DIR: &str = ".cyberctf-attack-vm";
pub fn dir(lab_dir: &Path) -> PathBuf {
    lab_dir.join(DIR)
}

/// A Vagrant box reference the launcher accepts: `owner/name`, plain characters only (it goes
/// into a generated Vagrantfile and onto a command line).
pub fn valid_box(b: &str) -> bool {
    let ok = |s: &str| !s.is_empty() && s.len() <= 64 && s.chars().all(|c| c.is_ascii_alphanumeric() || "-_.".contains(c));
    matches!(b.split_once('/'), Some((owner, name)) if ok(owner) && ok(name))
}

/// One lab network the attacker joins: the lab's name for it, the hypervisor's internal-network
/// name, the attacker's (free) address on it, the netmask.
#[derive(Debug, PartialEq)]
pub(crate) struct Link {
    pub net: String,
    pub intnet: String,
    pub ip: Ipv4Addr,
    pub mask: Ipv4Addr,
}

/// Where the attacker sits in the lab, read from the lab's generated Vagrantfile: the lab's name
/// (the VM-name prefix) and one link per lab network, at an address no machine uses.
pub(crate) fn plan(lab_vagrantfile: &str) -> Result<(String, Vec<Link>)> {
    let lab = vm::vm_names_from(lab_vagrantfile)
        .first()
        .and_then(|n| n.split(" · ").next().map(str::to_string))
        .ok_or_else(|| Error::Invalid("the lab's Vagrantfile names no machine".into()))?;
    let (ifaces, networks) = vm::vagrant_topology(lab_vagrantfile, &lab);
    let mut links = Vec::new();
    for n in networks {
        let (base, len) = parse_cidr(&n.subnet).ok_or_else(|| Error::Invalid(format!("network `{}` has no subnet", n.name)))?;
        let used: HashSet<Ipv4Addr> = ifaces.values().flatten().filter(|i| i.network == n.name).filter_map(|i| i.ip.parse().ok()).collect();
        let ip = free_address(base, len, &used).ok_or_else(|| Error::Invalid(format!("no free address on `{}` for the attack VM", n.name)))?;
        links.push(Link { intnet: format!("isoloom-{lab}-{}", n.name), net: n.name, ip, mask: mask_of(len) });
    }
    if links.is_empty() {
        return Err(Error::Invalid("the lab's Vagrantfile declares no network to join".into()));
    }
    Ok((lab, links))
}

fn parse_cidr(s: &str) -> Option<(Ipv4Addr, u8)> {
    let (ip, len) = s.split_once('/')?;
    let len: u8 = len.parse().ok()?;
    (len <= 30).then_some((ip.parse().ok()?, len))
}

fn mask_of(len: u8) -> Ipv4Addr {
    Ipv4Addr::from(if len == 0 { 0 } else { u32::MAX << (32 - len) })
}

/// The lowest host address from .2 (the gateway sits on .1) that no machine uses.
fn free_address(base: Ipv4Addr, len: u8, used: &HashSet<Ipv4Addr>) -> Option<Ipv4Addr> {
    let net = u32::from(base) & u32::from(mask_of(len));
    let size = 1u32 << (32 - len);
    (2..size - 1).map(|i| Ipv4Addr::from(net + i)).find(|a| !used.contains(a))
}

/// The attacker's Vagrantfile: one machine, the chosen box, NAT for the internet (the provider's
/// first adapter) and a NIC per lab network on the lab's internal networks.
pub(crate) fn vagrantfile(lab: &str, box_name: &str, links: &[Link]) -> String {
    let name = format!("{lab} · attacker");
    let mut out = format!(
        "# Generated by Cyber CTF: the attack VM beside the lab \"{lab}\". Don't edit: it is written at each start.\nVagrant.configure(\"2\") do |config|\n  config.vm.define \"attacker\" do |m|\n    m.vm.box = \"{box_name}\"\n    m.vm.hostname = \"attacker\"\n    m.vm.synced_folder \".\", \"/vagrant\", disabled: true\n    m.vm.boot_timeout = 900\n    # The provider's own NAT adapter (first NIC) gives it the internet, to install tools.\n"
    );
    for l in links {
        out.push_str(&format!(
            "    m.vm.network \"private_network\", ip: \"{}\", netmask: \"{}\", virtualbox__intnet: \"{}\", libvirt__network_name: \"{}\", libvirt__dhcp_enabled: false\n",
            l.ip, l.mask, l.intnet, l.intnet
        ));
    }
    out.push_str(&format!(
        "    m.vm.provider \"virtualbox\" do |v|\n      v.name = \"{name}\"\n      v.memory = 2048\n      v.cpus = 2\n    end\n    m.vm.provider \"vmware_desktop\" do |v|\n      v.vmx[\"displayname\"] = \"{name}\"\n      v.vmx[\"memsize\"] = \"2048\"\n      v.vmx[\"numvcpus\"] = \"2\"\n    end\n    m.vm.provider \"parallels\" do |v|\n      v.name = \"{name}\"\n      v.memory = 2048\n      v.cpus = 2\n    end\n  end\nend\n"
    ));
    out
}

/// Starts the attacker beside the lab (whose Vagrantfile is in `lab_vagrant_dir`), on the same
/// hypervisor. The first start downloads the box.
pub async fn start(lab_dir: &Path, lab_vagrant_dir: &Path, provider: Provider, box_name: &str, mut log: impl FnMut(String)) -> Result<()> {
    if !valid_box(box_name) {
        return Err(Error::Invalid(format!("invalid attack VM box `{box_name}` (expected owner/name)")));
    }
    let text = std::fs::read_to_string(lab_vagrant_dir.join("Vagrantfile")).map_err(Error::Io)?;
    let (lab, links) = plan(&text)?;
    let d = dir(lab_dir);
    std::fs::create_dir_all(&d).map_err(Error::Io)?;
    std::fs::write(d.join("Vagrantfile"), vagrantfile(&lab, box_name, &links)).map_err(Error::Io)?;
    log(format!("Starting the attack VM ({box_name}) next to the lab; the first start downloads the box, which can take a while…"));
    vm::discard_aborted_saved(&d, &mut log).await;
    stream("vagrant", &["up", "--provider", provider.id()], Some(&d), &[], &mut log).await?;
    log("Attack VM ready.".into());
    Ok(())
}

/// Destroys the attacker, finishing at the hypervisor by its exact VM name (as for the lab's
/// own VMs). Nothing to do when it was never started.
pub async fn stop(lab_dir: &Path, mut log: impl FnMut(String)) {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return;
    }
    log("Removing the attack VM…".into());
    let _ = stream("vagrant", &["destroy", "--force"], Some(&d), &[], &mut log).await;
    let names: HashSet<String> = vm::vm_names(&d).into_iter().collect();
    if !names.is_empty() {
        vm::recover_virtualbox(&names, &mut log).await;
        vm::recover_parallels(&names, &mut log).await;
    }
    let _ = std::fs::remove_dir_all(d.join(".vagrant"));
}

/// Parks the attacker with the lab (nothing to do when it was never started).
pub async fn park(lab_dir: &Path, mode: Park, log: impl FnMut(String)) -> Result<()> {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Ok(());
    }
    vm::park(&d, mode, &[], log).await
}

/// Brings a parked attacker back with the lab.
pub async fn resume(lab_dir: &Path, log: impl FnMut(String)) -> Result<()> {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Ok(());
    }
    vm::resume(&d, &[], log).await
}

/// The attacker's status, in the container attack box's shape: `image_present` is the box being
/// downloaded already, `ip`/`lab_network` its first lab address once running.
pub async fn status(lab_dir: &Path, box_name: &str) -> ExegolStatus {
    let d = dir(lab_dir);
    let image_present =
        run_read("vagrant", &["box", "list"], None).await.map(|out| out.lines().any(|l| l.split_whitespace().next() == Some(box_name))).unwrap_or(false);
    let (running, ip, lab_network) = if d.join("Vagrantfile").exists() {
        match vm::status(&d, &[]).await {
            Ok(s) => {
                let first = s.machines.into_iter().next();
                let ip = first.as_ref().map(|m| m.ip.clone()).unwrap_or_default();
                let net = first.and_then(|m| m.interfaces.into_iter().next()).map(|i| i.network).unwrap_or_default();
                (s.running, if s.running { ip } else { String::new() }, if s.running { net } else { String::new() })
            }
            Err(_) => (false, String::new(), String::new()),
        }
    } else {
        (false, String::new(), String::new())
    };
    ExegolStatus { image_present, running, ip, lab_network, shell_cmd: format!("cd {} && vagrant ssh", ssh::sh_quote(&d.to_string_lossy())) }
}

/// Opens the player's terminal on an SSH session into the attacker.
pub fn shell(lab_dir: &Path) -> Result<()> {
    let d = dir(lab_dir);
    if !d.join("Vagrantfile").exists() {
        return Err(Error::Invalid("the attack VM isn't started".into()));
    }
    let inner = format!("cd {} && exec vagrant ssh", ssh::sh_quote(&d.to_string_lossy()));
    exegol::open_terminal(&format!("sh -c {}", ssh::sh_quote(&inner)))
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;
    use std::net::Ipv4Addr;

    use super::{Link, free_address, plan, vagrantfile, valid_box};

    const LAB: &str = r#"
  config.vm.define "dc01" do |m|
    m.vm.network "private_network", ip: "192.168.56.30", netmask: "255.255.255.0", virtualbox__intnet: "isoloom-minilab-lab", libvirt__network_name: "isoloom-minilab-lab", libvirt__dhcp_enabled: false
    m.vm.provider "virtualbox" do |v|
      v.name = "minilab · dc01"
    end
  end
  config.vm.define "isoloom-controller" do |m|
    m.vm.network "private_network", ip: "192.168.56.253", netmask: "255.255.255.0", virtualbox__intnet: "isoloom-minilab-lab"
    m.vm.provider "virtualbox" do |v|
      v.name = "minilab · controller"
    end
  end
"#;

    #[test]
    fn plans_a_free_address_on_each_lab_network() {
        let (lab, links) = plan(LAB).unwrap();
        assert_eq!(lab, "minilab");
        // One link, on the lab's internal network, at the first free host address (.2: .1 is the
        // gateway, .30 and .253 are taken).
        assert_eq!(
            links,
            vec![Link { net: "lab".into(), intnet: "isoloom-minilab-lab".into(), ip: "192.168.56.2".parse().unwrap(), mask: "255.255.255.0".parse().unwrap() }]
        );
    }

    #[test]
    fn free_address_skips_taken_ones() {
        let used: HashSet<Ipv4Addr> = ["10.20.0.2", "10.20.0.3"].iter().map(|s| s.parse().unwrap()).collect();
        assert_eq!(free_address("10.20.0.0".parse().unwrap(), 24, &used), Some("10.20.0.4".parse().unwrap()));
        // A /30 has no host left once .2 is taken (.1 gateway, .3 broadcast).
        let used: HashSet<Ipv4Addr> = ["10.0.0.2".parse().unwrap()].into();
        assert_eq!(free_address("10.0.0.0".parse().unwrap(), 30, &used), None);
    }

    #[test]
    fn vagrantfile_joins_the_lab_networks_and_names_the_vm_after_the_lab() {
        let (lab, links) = plan(LAB).unwrap();
        let vf = vagrantfile(&lab, "kalilinux/rolling", &links);
        assert!(vf.contains("m.vm.box = \"kalilinux/rolling\""));
        assert!(vf.contains("virtualbox__intnet: \"isoloom-minilab-lab\""));
        assert!(vf.contains("ip: \"192.168.56.2\""));
        assert!(vf.contains("v.name = \"minilab · attacker\""));
        // No synced folder (nothing of the launcher's inside the attacker), NAT left for internet.
        assert!(vf.contains("disabled: true"));
    }

    #[test]
    fn boxes_are_owner_slash_name() {
        assert!(valid_box("kalilinux/rolling"));
        assert!(valid_box("generic/debian12"));
        assert!(!valid_box("kali"));
        assert!(!valid_box("owner/name; rm -rf /"));
        assert!(!valid_box("owner/name\"\nconfig"));
    }
}
